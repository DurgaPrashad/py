//! Local-first persistence. Everything lives under the app data directory:
//!
//! ```text
//! <app_data>/
//!   settings.json
//!   models/ggml-*.bin
//!   projects/<id>/project.json
//!   projects/<id>/source.<ext>
//!   projects/<id>/slides/*.jpg
//!   projects/<id>/thumbs/*.jpg
//! ```
//!
//! Project documents are owned by the frontend; the backend stores them as
//! opaque JSON and only guarantees atomic writes.

use std::fs;
use std::io::Write;
use std::path::{Component, Path, PathBuf};

use serde::Serialize;
use serde_json::Value;
use tauri::{AppHandle, Manager};

use crate::error::{err, CmdResult};

pub fn data_dir(app: &AppHandle) -> CmdResult<PathBuf> {
    let dir = app.path().app_data_dir()?;
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

pub fn projects_dir(app: &AppHandle) -> CmdResult<PathBuf> {
    let dir = data_dir(app)?.join("projects");
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

pub fn models_dir(app: &AppHandle) -> CmdResult<PathBuf> {
    let dir = data_dir(app)?.join("models");
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

/// Project ids are generated by the frontend (uuid v4). Reject anything that
/// could escape the projects directory.
fn validate_id(id: &str) -> CmdResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 64
        && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok { Ok(()) } else { err(format!("invalid project id: {id}")) }
}

/// Relative asset names (e.g. `slides/3.jpg`) must stay inside the project.
fn validate_relative(name: &str) -> CmdResult<()> {
    let path = Path::new(name);
    let ok = !name.is_empty()
        && path.components().all(|c| matches!(c, Component::Normal(_)));
    if ok { Ok(()) } else { err(format!("invalid asset path: {name}")) }
}

fn project_dir(app: &AppHandle, id: &str) -> CmdResult<PathBuf> {
    validate_id(id)?;
    Ok(projects_dir(app)?.join(id))
}

/// Write via a temp file + rename so a crash never leaves a truncated file.
pub fn write_atomic(path: &Path, bytes: &[u8]) -> CmdResult<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let tmp = path.with_extension("tmp");
    {
        let mut file = fs::File::create(&tmp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
    }
    fs::rename(&tmp, path)?;
    Ok(())
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AppPaths {
    data_dir: String,
    projects_dir: String,
    models_dir: String,
}

#[tauri::command]
pub fn app_paths(app: AppHandle) -> CmdResult<AppPaths> {
    Ok(AppPaths {
        data_dir: data_dir(&app)?.to_string_lossy().into_owned(),
        projects_dir: projects_dir(&app)?.to_string_lossy().into_owned(),
        models_dir: models_dir(&app)?.to_string_lossy().into_owned(),
    })
}

#[tauri::command]
pub fn storage_list_projects(app: AppHandle) -> CmdResult<Vec<Value>> {
    let mut out = Vec::new();
    for entry in fs::read_dir(projects_dir(&app)?)? {
        let entry = entry?;
        let file = entry.path().join("project.json");
        let Ok(text) = fs::read_to_string(&file) else { continue };
        match serde_json::from_str::<Value>(&text) {
            Ok(value) => out.push(value),
            Err(e) => log::warn!("skipping corrupt project {}: {e}", file.display()),
        }
    }
    Ok(out)
}

#[tauri::command]
pub fn storage_load_project(app: AppHandle, id: String) -> CmdResult<Value> {
    let file = project_dir(&app, &id)?.join("project.json");
    let text = fs::read_to_string(&file)
        .map_err(|e| format!("could not read presentation {id}: {e}"))?;
    Ok(serde_json::from_str(&text)?)
}

#[tauri::command]
pub fn storage_save_project(app: AppHandle, project: Value) -> CmdResult<()> {
    let Some(id) = project.get("id").and_then(Value::as_str) else {
        return err("project is missing an id");
    };
    let file = project_dir(&app, id)?.join("project.json");
    write_atomic(&file, serde_json::to_string_pretty(&project)?.as_bytes())
}

#[tauri::command]
pub fn storage_delete_project(app: AppHandle, id: String) -> CmdResult<()> {
    let dir = project_dir(&app, &id)?;
    if dir.exists() {
        fs::remove_dir_all(dir)?;
    }
    Ok(())
}

/// Copy the original presentation file into the project directory so the
/// project keeps working even if the user moves or deletes the original.
#[tauri::command]
pub fn storage_import_source(app: AppHandle, id: String, source_path: String) -> CmdResult<String> {
    let src = PathBuf::from(&source_path);
    if !src.is_file() {
        return err(format!("file not found: {source_path}"));
    }
    let ext = src
        .extension()
        .and_then(|e| e.to_str())
        .map(|e| e.to_ascii_lowercase())
        .unwrap_or_default();
    let dir = project_dir(&app, &id)?;
    fs::create_dir_all(&dir)?;
    let dest = dir.join(format!("source.{ext}"));
    fs::copy(&src, &dest)?;
    Ok(dest.to_string_lossy().into_owned())
}

/// Store a binary asset (slide image, thumbnail) sent as a raw IPC body.
/// Metadata travels in headers: `x-project-id` and `x-asset-name`.
#[tauri::command]
pub fn storage_write_asset(app: AppHandle, request: tauri::ipc::Request<'_>) -> CmdResult<String> {
    let header = |name: &str| -> CmdResult<String> {
        request
            .headers()
            .get(name)
            .and_then(|v| v.to_str().ok())
            .map(|s| s.to_string())
            .ok_or_else(|| format!("missing header {name}").into())
    };
    let id = header("x-project-id")?;
    let name = header("x-asset-name")?;
    validate_relative(&name)?;
    let tauri::ipc::InvokeBody::Raw(bytes) = request.body() else {
        return err("expected a raw binary body");
    };
    let path = project_dir(&app, &id)?.join(&name);
    write_atomic(&path, bytes)?;
    Ok(path.to_string_lossy().into_owned())
}

#[tauri::command]
pub fn storage_load_settings(app: AppHandle) -> CmdResult<Value> {
    let file = data_dir(&app)?.join("settings.json");
    match fs::read_to_string(&file) {
        Ok(text) => Ok(serde_json::from_str(&text).unwrap_or(Value::Null)),
        Err(_) => Ok(Value::Null),
    }
}

#[tauri::command]
pub fn storage_save_settings(app: AppHandle, settings: Value) -> CmdResult<()> {
    let file = data_dir(&app)?.join("settings.json");
    write_atomic(&file, serde_json::to_string_pretty(&settings)?.as_bytes())
}

/// Read a local file and return it as a binary IPC response (no JSON
/// encoding overhead). Used to hand PDFs to pdf.js.
#[tauri::command]
pub fn read_file_bytes(path: String) -> CmdResult<tauri::ipc::Response> {
    let bytes = fs::read(&path).map_err(|e| format!("could not read {path}: {e}"))?;
    Ok(tauri::ipc::Response::new(bytes))
}
